/**
 * 左侧侧边栏：每个「上侧选中项」一个独立 sidebar
 *
 * 规则：
 *  - 点击上侧大类（SOM/SBC/...）→ 显示该大类下全部二级/三级/产品
 *  - 点击上侧二级分类（Rockchip/Pi/...）→ 只显示该二级分类下的三级 + 产品内部目录
 *  - 首页、FAQ、下载等通用页不显示侧边栏（displayed_sidebar: null）
 *
 * 全部由 src/data/catalog.js 自动生成，加分类不用改这个文件。
 */
const { categories } = require('./src/data/catalog');

const sidebars = {};

for (const c of categories) {
  // 大类侧栏：整个大类目录树
  sidebars[c.id] = [{ type: 'autogenerated', dirName: c.dir }];
  // 二级侧栏：只含当前二级分类的目录树
  for (const g of c.groups) {
    sidebars[g.sidebarId] = [{ type: 'autogenerated', dirName: `${c.dir}/${g.dir}` }];
  }
}

sidebars.support = [
  { type: 'doc', id: 'support/overview', label: 'Support' },
  { type: 'doc', id: 'support/forum', label: 'Forum' },
  { type: 'doc', id: 'support/blog', label: 'Blog' },
];

module.exports = sidebars;
